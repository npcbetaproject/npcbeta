const { JSDOM } = require('jsdom');
const fs = require('node:fs');
const assert = require('node:assert/strict');

(async () => {
  const w = new JSDOM(fs.readFileSync('docs/index.html', 'utf8'), { url: 'https://example.com/npcbeta/', runScripts: 'outside-only' }).window;
  w.scrollTo = () => {};
  w.fetch = async path => ({ ok: true, json: async () => JSON.parse(fs.readFileSync('docs/' + path)) });
  w.localStorage.setItem('npc-beta-saved', JSON.stringify(['mira-fen', 'nessa-vale']));
  w.localStorage.setItem('npc-beta-session', JSON.stringify(['cassian-holt']));
  w.eval(['portraits', 'character-portraits', 'generator', 'locations', 'generated-visuals', 'session-board', 'app'].map(n => fs.readFileSync('docs/js/' + n + '.js', 'utf8')).join('\n') + '\nwindow.test = {state, visibleCharacters, setView};');
  await new Promise(resolve => setTimeout(resolve, 30));
  const d = w.document, t = w.test, saved = d.querySelector('#saved-filter');
  const ids = () => Array.from(t.visibleCharacters(), c => c.id);
  const change = (selector, value) => { const input = d.querySelector(selector); input.value = value; input.dispatchEvent(new w.Event(input.type === 'search' ? 'input' : 'change', { bubbles: true })); };
  const total = ids().length;
  assert(!saved.checked);
  assert.equal(d.querySelector('#saved-filter-label').textContent, 'Saved (2)');
  saved.click();
  assert.deepEqual(ids().sort(), ['mira-fen', 'nessa-vale']);
  change('#character-sort', 'name');
  assert.deepEqual(ids(), ['mira-fen', 'nessa-vale']);
  change('#character-search', 'smuggler');
  assert.deepEqual(ids(), ['nessa-vale']);
  d.querySelector('#role-filters input[value="faith-healing"]').click();
  assert.equal(ids().length, 0);
  assert.equal(d.querySelector('.empty-state').textContent, 'No saved NPCs match those filters.');
  change('#character-search', '');
  d.querySelector('[data-all-roles]').click();
  d.querySelector('#location-filters input[value="settlements"]').click();
  assert.deepEqual(ids().sort(), ['mira-fen', 'nessa-vale']);
  d.querySelector('.clear-filters').click();
  assert(!saved.checked);
  assert.equal(ids().length, total);
  assert.equal(t.state.sort, 'name');
  saved.click();
  t.setView('session');
  assert.deepEqual(ids(), ['cassian-holt']);
  t.setView('saved');
  assert(!d.querySelector('#saved-filter-group').hidden);
  assert.equal(t.state.view, 'library');
  assert.equal(w.location.hash, '#library');
  assert(saved.checked);
  assert.equal(d.querySelectorAll('[data-view="saved"]').length, 0);
  assert.deepEqual(ids().sort(), ['mira-fen', 'nessa-vale']);
  t.setView('library');
  d.querySelector('[data-save="mira-fen"]').click();
  assert.deepEqual(ids(), ['nessa-vale']);
  assert.equal(d.querySelector('#saved-filter-label').textContent, 'Saved (1)');
  d.querySelector('[data-save="nessa-vale"]').click();
  assert.equal(d.querySelector('.empty-state').textContent, 'No saved NPCs yet.');
  w.localStorage.setItem('npc-beta-saved', JSON.stringify(['mira-fen']));
  w.dispatchEvent(new w.StorageEvent('storage', { key: 'npc-beta-saved' }));
  assert.deepEqual(ids(), ['mira-fen']);
  assert.equal(d.querySelector('#saved-filter-label').textContent, 'Saved (1)');
  assert.equal(w.localStorage.getItem('npc-beta-session'), '["cassian-holt"]');
  w.close();
  console.log('PASS: Saved filter, count, search, role/location combination, sorting, clear, views, unsave, empty states and cross-tab updates');
})().catch(error => { console.error(error); process.exit(1); });
